import { readFileSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const registry = readFileSync(path.join(root, 'src', 'automation', 'command-registry.ts'), 'utf8');
const version = registry.match(/export const AUTOMATION_API_VERSION = (\d+) as const;/u)?.[1];
const commandIds = [...registry.matchAll(/^\s*commandId:\s*'([^']+)'/gmu)].map((match) => match[1]);
if (!version || commandIds.length === 0 || new Set(commandIds).size !== commandIds.length) {
  throw new Error('Automation Registry has no valid, unique command declarations.');
}
const declarationPath = path.join(root, 'docs', 'manual', 'scripts', 'automation-api.d.ts');
const declaration = [
  '// Generated by scripts/generate-automation-declarations.mjs; do not edit.',
  '// The public source contract supplies complete argument/result types.',
  "import type { WorldlineBoxAutomationScriptApi } from '../../../src/shared/automation-script-api';",
  "export type { WorldlineBoxAutomationScriptApi } from '../../../src/shared/automation-script-api';",
  `export declare const AUTOMATION_API_VERSION: ${version};`,
  'export type AutomationCommandId =',
  ...commandIds.map((id, index) => `  | '${id}'${index === commandIds.length - 1 ? ';' : ''}`),
  'export declare const worldlinebox: WorldlineBoxAutomationScriptApi;',
  '',
].join('\n');
mkdirSync(path.dirname(declarationPath), { recursive: true });
if (!existsSync(declarationPath) || readFileSync(declarationPath, 'utf8') !== declaration) {
  writeFileSync(declarationPath, declaration, 'utf8');
}
console.log(`[automation] API v${version}, ${commandIds.length} commands: docs/manual/scripts/automation-api.d.ts`);
