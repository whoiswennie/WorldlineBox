import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, expect, it } from 'vitest';
import { CompanionsStore } from '../../src/companions/store';
import { companionSearchTokens } from '../../src/shared/companion-search';
const roots: string[] = []; const stores: CompanionsStore[] = [];
afterEach(() => { for (const store of stores.splice(0)) store.close(); for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true }); });
function fixture() { const root = mkdtempSync(path.join(tmpdir(), 'companion-history-')); roots.push(root); const filename = path.join(root, 'messages.sqlite'); const store = new CompanionsStore(filename); stores.push(store); store.restoreBuiltin('gpt'); store.restoreBuiltin('kimi'); return { store, filename }; }
it('starts with explicitly added contacts only and explicitly opens an empty chat; hide, restore and dissolution survive restart', () => {
  const { store, filename } = fixture();
  expect(store.state().companions).toHaveLength(2); expect(store.state().conversations).toHaveLength(0);
  store.restoreBuiltin('gpt'); expect(store.state().conversations).toHaveLength(0);
  const room = store.openPrivate('gpt'); expect(store.messages({ conversationId: room.id }).messages).toEqual([]);
  const message = store.appendMessage({ conversationId: room.id, authorId: 'user', content: '保留私聊记录' });
  store.deleteConversation(room.id, 'hide'); expect(store.state().conversations).toEqual([]);
  expect(store.search({ query: '私聊记录' }).messages[0]?.id).toBe(message.id);
  expect(store.openPrivate('gpt').id).toBe(room.id);
  const group = store.createConversation('', ['gpt', 'kimi']);
  const source = store.appendMessage({ conversationId: group.id, authorId: 'user', content: '解散群聊验收', replyDirective: 'auto' });
  store.request({ type: 'work.enqueue', work: { id: 'pending', sourceMessageId: source.id, conversationId: group.id, companionId: 'gpt', status: 'queued', proactive: false, createdAt: source.createdAt, updatedAt: source.createdAt } });
  store.deleteConversation(group.id, 'dissolve');
  expect(store.request({ type: 'work.claim' }).work).toBeUndefined();
  store.request({ type: 'work.status', id: 'pending', status: 'interrupted' });
  store.setReplyStatus(group.id, source.id, 'pending');
  expect(store.replyCheckpoint(group.id, source.id)?.status).toBe('cancelled');
  expect(store.getMessage(source.id).content).toBe('解散群聊验收');
  expect(store.search({ query: '解散群聊验收' }).messages).toHaveLength(0);
  expect(() => store.appendMessage({ conversationId: group.id, authorId: 'user', content: '不能复活' })).toThrow('解散');
  expect(() => store.request({ type: 'conversation.reopen', id: group.id })).toThrow('解散');
  expect(() => store.deleteConversation(room.id, 'dissolve')).toThrow('只能解散群聊');
  store.close(); stores.splice(stores.indexOf(store), 1);
  const reopened = new CompanionsStore(filename); stores.push(reopened);
  expect(reopened.state().conversations.map(item => item.id)).toEqual([room.id]);
  expect(reopened.createConversation('', ['kimi', 'gpt']).id).not.toBe(group.id);
});
it('pages in both directions and locates a bounded context without gaps or duplicate timestamp ambiguity', () => {
  const { store } = fixture(); const room = store.openPrivate('gpt');
  const all = Array.from({ length: 235 }, (_, index) => store.appendMessage({ conversationId: room.id, authorId: 'user', content: '第 ' + index + ' 条' }));
  const latest = store.messages({ conversationId: room.id });
  expect(latest.messages.map(item => item.id)).toEqual(all.slice(-50).map(item => item.id)); expect(latest.hasMore).toBe(true); expect(latest.hasNewer).toBe(false);
  const older = store.messages({ conversationId: room.id, before: latest.messages[0]!.sequence });
  const newer = store.messages({ conversationId: room.id, after: older.messages.at(-1)!.sequence });
  expect(newer.messages.map(item => item.id)).toEqual(latest.messages.map(item => item.id));
  const around = store.messages({ conversationId: room.id, around: all[70]!.id });
  expect(around.messages.map(item => item.id)).toEqual(all.slice(46, 96).map(item => item.id)); expect(around.hasMore && around.hasNewer).toBe(true);
  expect(store.messages({ conversationId: room.id, after: all[1]!.sequence, before: all[10]!.sequence }).messages.map(item => item.id)).toEqual(all.slice(2, 10).map(item => item.id));
  const other = store.openPrivate('kimi'); expect(() => store.messages({ conversationId: other.id, around: all[70]!.id })).toThrow(/不属于|属于别的会话/u);
});
it('indexes short Chinese, literal punctuation, normalized width, filename references and filtered cursor pages', () => {
  const { store } = fixture(); const room = store.createConversation('', ['gpt', 'kimi']);
  store.registerAttachment({ attachment: { id: 'document', name: '星海合同-v2.pdf', mime: 'application/pdf', size: 40 }, relativePath: 'attachments/document.pdf', sourcePath: 'C:\\资料\\星海合同-v2.pdf' });
  store.registerAttachment({ attachment: { id: 'photo', name: '猫.png', mime: 'image/png', size: 40 }, relativePath: 'attachments/photo.png' });
  const doc = store.appendMessage({ conversationId: room.id, authorId: 'user', content: '读这个', attachmentIds: ['document'] });
  const photo = store.appendMessage({ conversationId: room.id, authorId: 'kimi', content: '猫', attachmentIds: ['photo'] });
  const literal = store.appendMessage({ conversationId: room.id, authorId: 'gpt', content: 'ＡＢＣ 100%_ "对白" https://example.com/report' });
  for (const query of ['合同', '星海合同', 'pdf']) expect(store.search({ query }).messages.map(item => item.id)).toContain(doc.id);
  expect(store.search({ query: '猫' }).messages.map(item => item.id)).toEqual([photo.id]);
  for (const query of ['abc', '100%_', '"对白"', 'example.com', '对白 abc']) expect(store.search({ query }).messages.map(item => item.id)).toEqual([literal.id]);
  expect(store.search({ query: '', category: 'files' }).messages.map(item => item.id)).toEqual([doc.id]);
  expect(store.search({ query: '', category: 'images' }).messages.map(item => item.id)).toEqual([photo.id]);
  expect(store.search({ query: '', category: 'links', authorId: 'gpt' }).messages.map(item => item.id)).toEqual([literal.id]);
  expect(store.search({ query: '', from: '2099-01-01T00:00:00.000Z' }).messages).toEqual([]);
  const first = store.search({ query: '', conversationId: room.id, limit: 2, compact: true });
  expect(first.messages).toEqual([]); expect(first.searchPage.items).toHaveLength(2); expect(first.searchPage.hasMore).toBe(true);
  store.appendMessage({ conversationId: room.id, authorId: 'user', content: '新插入消息' });
  const next = store.search({ query: '', conversationId: room.id, before: first.searchPage.nextBefore, snapshot: first.searchPage.snapshot });
  expect(next.messages.map(item => item.id)).toEqual([doc.id]);
});
it('retains the current schema, contact settings, message index and attachments after restart', () => {
  const { store, filename } = fixture(); const room = store.openPrivate('gpt');
  const welcome = store.openPrivate('kimi'); store.appendMessage({ conversationId: welcome.id, authorId: 'kimi', content: '自动欢迎', clientId: 'builtin-welcome-kimi', kind: 'notice' });
  for (let index = 0; index < 1100; index++) store.appendMessage({ conversationId: room.id, authorId: 'user', content: '历史合同 ' + index });
  const profile = store.state().companions.find(companion => companion.id === 'gpt')!;
  store.updateCompanion('gpt', { ...profile, name: '保留的名字', persona: '保留的人设' });
  store.registerAttachment({ attachment: { id: 'retained-avatar', name: 'avatar.png', mime: 'image/png', size: 32 }, relativePath: 'attachments/retained-avatar.png' });
  store.close(); stores.splice(stores.indexOf(store), 1);
  let reopened = new CompanionsStore(filename); stores.push(reopened);
  expect(reopened.state().conversations).toHaveLength(2);
  expect(reopened.state().companions.find(companion => companion.id === 'gpt')).toMatchObject({ name: '保留的名字', persona: '保留的人设' });
  expect(reopened.getAttachment('retained-avatar').attachment.name).toBe('avatar.png');
  expect(reopened.search({ query: '合同' }).messages).toHaveLength(30);
  expect(reopened.request({ type: 'memory.status', companionId: 'gpt' }).memoryStatus).toMatchObject({ pending: 1100, running: 0, failed: 0, memories: 0 });
  reopened.close(); stores.splice(stores.indexOf(reopened), 1);
  reopened = new CompanionsStore(filename); stores.push(reopened);
  expect(reopened.backfillSearchIndex()).toBe(true);
  expect(reopened.search({ query: '合同' }).messages).toHaveLength(30);
  expect(reopened.backfillSearchIndex()).toBe(true);
  reopened.openPrivate('gpt');
  // Normal writes update the indexed content; the old term must disappear.
  const source = reopened.appendMessage({ conversationId: room.id, authorId: 'user', content: '开始', replyDirective: 'auto' });
  const bubble = reopened.appendMessage({ conversationId: room.id, authorId: 'gpt', content: '', loopStep: 0 });
  reopened.request({ type: 'loop.save', checkpoint: { conversationId: room.id, sourceMessageId: source.id, companionId: 'gpt', messageId: bubble.id, status: 'running', supplements: [], turns: [{ text: '旧字词', rawText: '旧字词', calls: [], results: [] }] } });
  expect(reopened.search({ query: '旧字词' }).messages).toHaveLength(0);
  reopened.request({ type: 'loop.save', checkpoint: { conversationId: room.id, sourceMessageId: source.id, companionId: 'gpt', messageId: bubble.id, status: 'done', supplements: [], turns: [{ text: '新字词', rawText: '新字词', calls: [], results: [] }] } });
  expect(reopened.search({ query: '旧字词' }).messages).toHaveLength(0); expect(reopened.search({ query: '新字词' }).messages).toHaveLength(1);
  expect(companionSearchTokens('Ａ')).toBe(companionSearchTokens('a'));
});
